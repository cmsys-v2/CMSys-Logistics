export function CrestMark({
  className,
  size = 44,
  glow = true,
  priority = false,
}: {
  className?: string;
  size?: number;
  glow?: boolean;
  priority?: boolean;
}) {
  return (
    <span
      className={cn("relative inline-flex shrink-0 items-center justify-center", className)}
      style={{ width: size, height: size }}
    >
      {glow && (
        <span
          aria-hidden
          className="pointer-events-none absolute inset-0 rounded-full blur-xl opacity-60"
          style={{
            background:
              "radial-gradient(circle, color-mix(in srgb, var(--gold) 60%, transparent), transparent 68%)",
          }}
        />
      )}
      <Image
        src="/brand/crest.svg"
        alt="CMSys — SLN Logistics crest"
        width={size}
        height={size}
        priority={priority}
        unoptimized
        className="relative z-10 h-full w-full object-contain drop-shadow-[0_6px_14px_rgba(0,0,0,0.45)]"
      />
    </span>
  );
}

